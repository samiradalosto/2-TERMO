-- 6. Criar auditoria_preco

CREATE TABLE AUDITORIA_PRECO2 (
    ID_AUDITORIA INT AUTO_INCREMENT,
    ID_PRODUTO INT NOT NULL,
    PRECO_ANTERIOR DECIMAL(10,2),
    PRECO_NOVO DECIMAL(10,2),
    ALTERADO_EM DATETIME DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_AUDITORIA),
    FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO)
);

-- 7. Trigger AFTER UPDATE de preço

DELIMITER $$

CREATE TRIGGER TRG_PRODUTO_PRECO2_UPDATE
AFTER UPDATE ON PRODUTO
FOR EACH ROW
BEGIN
    IF OLD.PRECO <> NEW.PRECO THEN
        INSERT INTO AUDITORIA_PRECO
        (ID_PRODUTO, PRECO_ANTERIOR, PRECO_NOVO)
        VALUES
        (NEW.ID_PRODUTO, OLD.PRECO, NEW.PRECO);
    END IF;
END $$

DELIMITER ;

-- 8. Trigger BEFORE UPDATE impedindo estoque negativo
DELIMITER $$
CREATE TRIGGER TRG_ESTOQUE_BEFORE2_UPDATE
BEFORE UPDATE ON ESTOQUE
FOR EACH ROW
BEGIN
    IF NEW.QUANTIDADE < 0 THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'ESTOQUE NÃO PODE FICAR NEGATIVO';
    END IF;
END $$
DELIMITER; log_exclusao_produto

-- 10. Trigger AFTER DELETE
DELIMITER $$
CREATE TRIGGER TRG_PRODUTO_AFTER2_DELETE
AFTER DELETE ON PRODUTO
FOR EACH ROW
BEGIN
    INSERT INTO LOG_EXCLUSAO_PRODUTO(ID_PRODUTO, NOME_PRODUTO)
    VALUES (OLD.ID_PRODUTO, OLD.NOME);
END $$
DELIMITER;

