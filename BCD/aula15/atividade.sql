-- 3. FUNCTION CALCULAR_DESCONTO
DELIMITER $$
CREATE FUNCTION CALCULANDO_DESCONTO
(
    P_VALOR DECIMAL(10,2),
    P_PONTOS INT
)
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
    DECLARE V_PERCENTUAL DECIMAL (5,2);
    IF P_PONTOS >= 300 THEN
        SET V_PERCENTUAL = 0.10;
    ELSEIF P_PONTOS >= 220 THEN
        SET V_PERCENTUAL = 0.05;
    ELSE
        SET V_PERCENTUAL = 0;
    END IF;
    RETURN P_VALOR * P_PERCENTUAL;
END $$
DELIMITER;

